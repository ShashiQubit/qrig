#!/usr/bin/env python3
"""The four-step MQT testing pipeline, with a real 8-equation optimiser in step 2.

This is the script from the project brief with the stub in step 2 replaced by qrig's
Lean-verified DAG optimiser, and updated for the current MQT APIs
(``mqt.bench`` 2.x: ``get_benchmark(benchmark, BenchmarkLevel.ALG, circuit_size)``;
``mqt.qcec`` 3.x: ``EquivalenceCriterion`` lives in ``mqt.qcec.pyqcec``).

    pip install qiskit mqt.bench mqt.qcec
    python benchmarks/mqt_quickstart.py [benchmark] [qubits]
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from mqt import qcec
from mqt.bench import BenchmarkLevel, get_benchmark
from mqt.qcec.pyqcec import EquivalenceCriterion
from qiskit import QuantumCircuit
from qiskit.converters import circuit_to_dag, dag_to_circuit

from qrig.dag import PeepholeStats, optimize_dag


# ==========================================
# STEP 1: Ingest standard multi-controlled benchmarks
# ==========================================
def get_test_benchmark(name: str = "grover", qubits: int = 5) -> QuantumCircuit:
    """Fetch a raw algorithmic benchmark from MQT Bench and expose MCX/MCPhase gates."""
    qc = get_benchmark(name, BenchmarkLevel.ALG, qubits)
    return qc.decompose()


# ==========================================
# STEP 2: 8-equation optimiser on the Qiskit DAG
# ==========================================
def run_8_equation_optimizer(circuit: QuantumCircuit) -> tuple[QuantumCircuit, PeepholeStats]:
    """Walk the DAG topologically and rewrite with the control equations.

    Each DAG node is read as a multiply controlled one-qubit gate; the verified core
    (C code generated by Lean from ``Qrig/Core/Peephole.lean``) applies equations
    (a) fusion, (b) identity, (d) colour change, (e) complementarity and (f)
    commutation, and ``peephole_sound`` (Lean) proves the result has exactly the same
    action on every state.  Measurements/barriers stay in place.
    """
    dag = circuit_to_dag(circuit)
    stats = PeepholeStats()
    optimized_dag = optimize_dag(dag, window=128, fuel=16, stats=stats)
    return dag_to_circuit(optimized_dag), stats


# ==========================================
# STEP 3: Execution and metric analysis
# ==========================================
def execute_benchmark_run(name: str = "grover", qubit_count: int = 5) -> bool:
    print("=== [1/4] Fetching Target Circuit from MQT Bench ===")
    raw_circuit = get_test_benchmark(name, qubit_count)
    print(f"{name}, {raw_circuit.num_qubits} qubits: {dict(raw_circuit.count_ops())}")

    print("\n=== [2/4] Running 8-Equation Optimizer (Lean-verified core) ===")
    optimized_circuit, stats = run_8_equation_optimizer(raw_circuit)
    print("rule applications:", stats.rules)

    print("\n=== [3/4] Compiling Benchmark Performance ===")
    metrics = {
        "Raw Depth": raw_circuit.depth(),
        "Raw Gate Count": len(raw_circuit.data),
        "Optimized Depth": optimized_circuit.depth(),
        "Optimized Gate Count": len(optimized_circuit.data),
    }
    for label, val in metrics.items():
        print(f"**{label}:** {val}")

    # ==========================================
    # STEP 4: Verification via MQT QCEC
    # ==========================================
    print("\n=== [4/4] Verifying Equivalence via MQT QCEC ===")
    result = qcec.verify(raw_circuit, optimized_circuit)
    print(f"**Functional Equivalence Status:** {result.equivalence}")
    ok = result.equivalence in (EquivalenceCriterion.equivalent,
                                EquivalenceCriterion.equivalent_up_to_global_phase)
    if ok:
        print("SUCCESS: optimisation verified equivalent to the raw algorithm.")
    else:
        print("FAILURE: optimisation altered the circuit.")
    return ok


if __name__ == "__main__":
    bench = sys.argv[1] if len(sys.argv) > 1 else "grover"
    n = int(sys.argv[2]) if len(sys.argv) > 2 else 5
    sys.exit(0 if execute_benchmark_run(bench, n) else 1)
